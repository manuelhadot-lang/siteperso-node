const rowCache = new Map();

function glcdColsToRows(c0, c1, c2, c3, c4) {
    const rows = new Uint8Array(8);
    const cols = [c0, c1, c2, c3, c4];
    for (let c = 0; c < 5; c++) {
        const col = cols[c];
        for (let j = 0; j < 8; j++) {
            if (col & (1 << j)) rows[j] |= 1 << (4 - c);
        }
    }
    return rows;
}

function getGlcdAsciiRows(code) {
    if (code < 0x20 || code > 0x7e) return SPACE_GLYPH;
    if (!rowCache.has(code)) {
        const off = (code - 0x20) * 5;
        rowCache.set(
            code,
            glcdColsToRows(
                GLCD_COLS[off],
                GLCD_COLS[off + 1],
                GLCD_COLS[off + 2],
                GLCD_COLS[off + 3],
                GLCD_COLS[off + 4]
            )
        );
    }
    return rowCache.get(code);
}

function accentedGfxGlyph(baseCode, row0, row1) {
    const rows = new Uint8Array(getGlcdAsciiRows(baseCode));
    if (row0 !== undefined) rows[0] = row0 & 0x1f;
    if (row1 !== undefined) rows[1] = row1 & 0x1f;
    return rows;
}

/** Glyphe TFT : Adafruit GFX pour ASCII, HD44780 pour Latin-1 (é, è…). */
export function getGfxGlyph(ch) {
    const code = ch.charCodeAt(0);
    if (code >= 0x20 && code <= 0x7e) return getGlcdAsciiRows(code);
    const acc = ACCENTED_LATIN.get(code);
    if (acc) return accentedGfxGlyph(acc.base, acc.r0, acc.r1);
    return getHd44780Glyph(ch);
}
