const SPACE_GLYPH = new Uint8Array(8);

/** @returns {Uint8Array} */
export function getHd44780Glyph(ch) {
    const code = ch.charCodeAt(0);
    if (code >= 0x20 && code <= 0x7f) {
        const off = (code - 0x20) * 8;
        return FONT.subarray(off, off + 8);
    }
    return SPACE_GLYPH;
}
